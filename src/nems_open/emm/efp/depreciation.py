"""EFP investment tax credit, book depreciation, tax depreciation and AFUDC tax savings:
ELITC, ELBKDP, ELTXDP, ELTSAF (uefp.f).

Each routine takes the state dict `s` and changes it in place. Most accounts are
REAL*4, and so are several that read like integers (EOBKLF, ESBKLF, ESLCP, ESTXRC,
ESTXRP, ESTXLF, EOTXLF): where one is assigned to an INTEGER (NRETIR, NSTRT, K, L)
the value is truncated toward zero, as Fortran does. Plant types: EIPROD=12 (1-12
production), EITRAN=13, EIDIST=14, NPTYP=14, EICAN=6 (cancelled plant).
"""

from nems_open.emm.efp.common import f32, i

NPTYP = 14
EIPROD, EITRAN, EIDIST, EICAN = 12, 13, 14, 6


def _int(x) -> int:
    """REAL assigned to INTEGER: truncate toward zero."""
    return int(x)


def _old_retire(eobklf, j, n, iyr, efpsyr, uhbsyr) -> int:
    """NRETIR = EOBKLF(J,N) - IYR + EFPSYR - UHBSYR (REAL*4 arithmetic, truncated)."""
    return _int(f32(f32(f32(eobklf[j, n] - f32(iyr)) + f32(efpsyr)) - f32(uhbsyr)))


def elitc(s):
    """Investment tax credit accounts (ELITC), both ownership types."""
    curiyr = i(s, "curiyr")
    jk = i(s, "efpsyr") - i(s, "uhbsyr")
    estshr, esftxr, esflpr = s["estshr"], s["esftxr"], s["esflpr"]
    eraitc, erfitc, ernitc, erditc = s["eraitc"], s["erfitc"], s["ernitc"], s["erditc"]
    eoaitc, eobklf, esbklf, eslcp, esritc = s["eoaitc"], s["eobklf"], s["esbklf"], s["eslcp"], s["esritc"]
    ebditc, ebasvl, ebycwp = s["ebditc"], s["ebasvl"], s["ebycwp"]
    ebptyp, ebsyr = s["ebptyp"], s["ebsyr"]
    eovyrs = i(s, "eovyrs")
    iyritc, jyritc = i(s, "iyritc"), i(s, "jyritc")

    for n in (1, 2):
        if estshr[n] == 0.0:
            continue
        eraitc[n] = f32(0.0)
        erfitc[n] = f32(0.0)
        ernitc[n] = f32(0.0)
        if esftxr[n] == 0.0:
            continue
        xitcd = f32(0.0)
        # amortization of deferred ITC on existing assets
        for j in range(1, NPTYP + 1):
            nstrt = jk - curiyr + 1
            if nstrt >= 1:
                erditc[n] = f32(erditc[n] + f32(eoaitc[nstrt, j, n] * eobklf[j, n]))
            else:
                nstrt = 1
            for iyr in range(nstrt, eovyrs + 1):
                nretir = _int(f32(f32(eobklf[j, n] - f32(iyr)) + f32(jk)))
                if curiyr <= nretir:
                    eraitc[n] = f32(eoaitc[iyr, j, n] + eraitc[n])
        # ITC generated by new builds, split between flow-through and deferred
        for b in range(1, i(s, "ebnum") + 1):
            j = int(ebptyp[b])
            syr = int(ebsyr[b])
            nstrt = _int(f32(f32(f32(syr) - eslcp[j]) + f32(1.0)))
            nretir = _int(f32(f32(syr) + esbklf[j, n]))
            if curiyr >= nstrt and curiyr < nretir:
                if curiyr <= syr:
                    gitc = f32(esritc[j] * ebycwp[b, n])
                    if curiyr >= iyritc and nstrt >= jyritc:
                        gitc = f32(0.0)
                    erfitc[n] = f32(f32(gitc * esflpr[n]) + erfitc[n])
                    xitcdp = f32(gitc * f32(f32(1.0) - esflpr[n]))
                    ebditc[b, n] = f32(ebditc[b, n] + xitcdp)
                    xitcd = f32(xitcd + xitcdp)
                    # post-TEFRA: lower the tax basis by half the deferred ITC
                    if curiyr == syr:
                        ebasvl[b, n] = f32(ebasvl[b, n] - f32(f32(0.5) * ebditc[b, n]))
                        eraitc[n] = f32(f32(ebditc[b, n] / esbklf[j, n]) + eraitc[n])
                else:
                    eraitc[n] = f32(f32(ebditc[b, n] / esbklf[j, n]) + eraitc[n])
        ernitc[n] = f32(xitcd - eraitc[n])
        erditc[n] = f32(erditc[n] + ernitc[n])


def elbkdp(s, nrgn, icall):
    """Book depreciation and tax depreciation without acceleration (ELBKDP).
    nrgn and icall are not used by the Fortran body."""
    curiyr = i(s, "curiyr")
    efpsyr, uhbsyr = i(s, "efpsyr"), i(s, "uhbsyr")
    eovyrs = i(s, "eovyrs")
    estshr = s["estshr"]
    ertdw1, erbde1, erbde2, erbtir, ercnad = s["ertdw1"], s["erbde1"], s["erbde2"], s["erbtir"], s["ercnad"]
    epadoc, episoc = s["epadoc"], s["episoc"]
    eobklf, eodepr, esbklf = s["eobklf"], s["eodepr"], s["esbklf"]
    eobkvl, eoasvl, eoabde = s["eobkvl"], s["eoasvl"], s["eoabde"]
    ebbkvl, ebserp, ebabde = s["ebbkvl"], s["ebserp"], s["ebabde"]
    ebptyp, ebsyr = s["ebptyp"], s["ebsyr"]
    erabdl, erabde, erbde, erbded, ertdwo = s["erabdl"], s["erabde"], s["erbde"], s["erbded"], s["ertdwo"]
    erbl, ertup, ercnbv = s["erbl"], s["ertup"], s["ercnbv"]
    erbvye = {}  # local ERBVYE(16,2), REAL*4

    for n in (1, 2):
        if estshr[n] == 0.0:
            continue
        ertdw1[n] = f32(0.0)
        erbde1[n] = f32(0.0)
        erbde2[n] = f32(0.0)
        erbtir[n] = f32(0.0)
        ercnad[n] = f32(0.0)
        for j in range(1, NPTYP + 1):
            erbvye[j, n] = f32(0.0)
            epadoc[j, n] = f32(0.0)
            episoc[j, n] = f32(0.0)

        # existing assets
        jy = max(efpsyr - uhbsyr - curiyr + 1, 1)
        for j in range(1, NPTYP + 1):
            for iyr in range(jy, eovyrs + 1):
                nretir = _old_retire(eobklf, j, n, iyr, efpsyr, uhbsyr)
                if nretir >= curiyr:
                    if nretir == curiyr:
                        erbtir[n] = f32(eobkvl[iyr, j, n] + erbtir[n])
                    else:
                        ertdw1[n] = f32(f32(eodepr[j, n] * eoasvl[iyr, j, n]) + ertdw1[n])
                        bde = f32(f32(eobkvl[iyr, j, n] - eoabde[iyr, j, n]) / f32(nretir - curiyr))
                        erbde1[n] = f32(bde + erbde1[n])
                        eoabde[iyr, j, n] = f32(bde + eoabde[iyr, j, n])

        # new assets
        for b in range(1, i(s, "ebnum") + 1):
            j = int(ebptyp[b])
            syr = int(ebsyr[b])
            nretir = _int(f32(f32(syr) + esbklf[j, n]))
            if syr <= curiyr and nretir >= curiyr:
                if syr == curiyr:
                    bde = f32(f32(ebbkvl[b, n] / esbklf[j, n]) * ebserp[b])
                    erbvye[j, n] = f32(ebbkvl[b, n] + erbvye[j, n])
                    if j == EICAN:
                        ercnad[n] = f32(f32(ercnad[n] + ebabde[b, n]) + bde)
                elif nretir == curiyr:
                    bde = f32(ebbkvl[b, n] - ebabde[b, n])
                    erbtir[n] = f32(ebbkvl[b, n] + erbtir[n])
                else:
                    den = f32(esbklf[j, n] - f32(f32(f32(curiyr - syr) + ebserp[b]) - f32(1.0)))
                    bde = f32(f32(ebbkvl[b, n] - ebabde[b, n]) / den)
                    erbvye[j, n] = f32(ebbkvl[b, n] + erbvye[j, n])
                    if j == EICAN:
                        ercnad[n] = f32(f32(ercnad[n] + ebabde[b, n]) + bde)
                erbde2[n] = f32(bde + erbde2[n])
                ebabde[b, n] = f32(bde + ebabde[b, n])
                if nretir != curiyr:
                    epadoc[j, n] = f32(epadoc[j, n] + ebabde[b, n])

        # combine old and new, adjust for retirements
        ertdwo[n] = ertdw1[n]
        erbde[n] = f32(erbde2[n] + erbde1[n])
        erabde[n] = f32(f32(erabdl[n] + erbde[n]) - erbtir[n])
        erbde[n] = f32(erbde[n] + erbded[n])

        # balance sheet asset entries.
        # Quirk kept: JYR is computed, then overwritten with MAX(JY, 1), i.e. JY's own value.
        jyr = max(jy, 1)
        for k in range(1, 5):
            erbl[k, n] = f32(0.0)
        for ip in range(1, NPTYP + 1):
            for iyr in range(jyr, eovyrs + 1):
                nretir = _old_retire(eobklf, ip, n, iyr, efpsyr, uhbsyr)
                if nretir > curiyr:
                    if ip <= EIPROD:
                        erbl[1, n] = f32(erbl[1, n] + eobkvl[iyr, ip, n])
                    if ip == EITRAN:
                        erbl[2, n] = f32(erbl[2, n] + eobkvl[iyr, ip, n])
                    if ip == EIDIST:
                        erbl[3, n] = f32(erbl[3, n] + eobkvl[iyr, ip, n])
                    if ip > EIDIST:
                        erbl[4, n] = f32(erbl[4, n] + eobkvl[iyr, ip, n])
                    episoc[ip, n] = f32(episoc[ip, n] + eobkvl[iyr, ip, n])
                    epadoc[ip, n] = f32(epadoc[ip, n] + eoabde[iyr, ip, n])
        for k in range(1, NPTYP + 1):
            if k <= EIPROD:
                erbl[1, n] = f32(erbl[1, n] + erbvye[k, n])
            if k == EIDIST:
                erbl[3, n] = f32(erbl[3, n] + erbvye[k, n])
            if k == EITRAN:
                erbl[2, n] = f32(erbl[2, n] + erbvye[k, n])
            if k > EIDIST:
                erbl[4, n] = f32(erbl[4, n] + erbvye[k, n])
            episoc[k, n] = f32(episoc[k, n] + erbvye[k, n])
        ercnbv[n] = erbvye[EICAN, n]
        ertup[n] = f32(f32(f32(erbl[1, n] + erbl[2, n]) + erbl[3, n]) + erbl[4, n])


def eltxdp(s, nrgn, icall):
    """Tax depreciation (ELTXDP): public utilities zeroed, private utilities computed.
    nrgn and icall are not used by the Fortran body."""
    curiyr = i(s, "curiyr")
    efpsyr, uhbsyr = i(s, "efpsyr"), i(s, "uhbsyr")
    eovyrs = i(s, "eovyrs")
    irsyp, irsytd, irsyt2 = i(s, "irsyp"), i(s, "irsytd"), i(s, "irsyt2")
    estshr, esftxr, esflpr = s["estshr"], s["esftxr"], s["esflpr"]
    ertde1, ertde2, eratsf, eratsd = s["ertde1"], s["ertde2"], s["eratsf"], s["eratsd"]
    ertdw2, erpdtb, ertdwo, ertde = s["ertdw2"], s["erpdtb"], s["ertdwo"], s["ertde"]
    erprdf, ertdrg, erpdfl, ertdw1 = s["erprdf"], s["ertdrg"], s["erpdfl"], s["ertdw1"]
    eoasvl, eotxlf, estxrc, estxrp, estxrs = s["eoasvl"], s["eotxlf"], s["estxrc"], s["estxrp"], s["estxrs"]
    estxlf, esbklf, esdepr = s["estxlf"], s["esbklf"], s["esdepr"]
    condr, condrn, icontp = s["condr"], s["condrn"], s["icontp"]
    ebasvl, ebserp, ebptyp, ebsyr = s["ebasvl"], s["ebserp"], s["ebptyp"], s["ebsyr"]
    zero, one, half = f32(0.0), f32(1.0), f32(0.5)

    # public utilities: zeroed (ESTSHR is not tested here)
    n = 2
    for arr in (ertde1, ertde2, eratsf, eratsd, ertdw2, erpdtb, ertdwo, ertde, erprdf, ertdrg):
        arr[n] = zero

    # private utilities
    n = 1
    if estshr[n] == 0.0:
        return
    ertde1[n] = zero
    ertde2[n] = zero
    eratsf[n] = zero
    eratsd[n] = zero
    ertdw2[n] = zero

    jy = max(efpsyr - (uhbsyr + curiyr - 1), 1)

    # existing assets, by vintage
    for j in range(1, NPTYP + 1):
        for iyr in range(jy, eovyrs + 1):
            if eoasvl[iyr, j, n] > 0.0:
                l = (curiyr + uhbsyr) - (efpsyr - iyr + 1) + 1
                if iyr <= efpsyr - 1987 + 1:
                    ertde1[n] = f32(ertde1[n] + f32(condr[l, int(icontp[j])] * eoasvl[iyr, j, n]))
                elif iyr < efpsyr - 1981 + 2:
                    k = _int(estxrc[j, n])
                    if l <= estxrp[k]:
                        ertde1[n] = f32(ertde1[n] + f32(estxrs[k, l] * f32(f32(0.95) * eoasvl[iyr, j, n])))
                else:
                    temp1 = f32(eotxlf[j, n] - f32(l - 1))
                    temp1 = max(temp1, zero)
                    temp2 = f32(f32(eotxlf[j, n] * f32(eotxlf[j, n] + one)) * half)
                    sydtdr = f32(temp1 / temp2)
                    sydtdr = max(sydtdr, zero)
                    ertde1[n] = f32(ertde1[n] + f32(sydtdr * eoasvl[iyr, j, n]))

    # excess of tax over book depreciation, existing assets
    if erpdtb[n] > 0.0:
        excess = f32(esftxr[n] * f32(ertde1[n] - ertdw1[n]))
        eratsd[n] = f32(excess * f32(one - esflpr[n]))
        eratsf[n] = f32(excess * esflpr[n])
        erpdtb[n] = f32(erpdtb[n] + eratsd[n])
        # Quirk kept: the negative-balance correction hits ERATSD twice.
        if erpdtb[n] < 0.0:
            eratsd[n] = f32(eratsd[n] - erpdtb[n])
        if erpdtb[n] < 0.0:
            eratsd[n] = f32(eratsd[n] - erpdtb[n])
            erpdtb[n] = zero

    # new assets
    for b in range(1, i(s, "ebnum") + 1):
        syr = int(ebsyr[b])
        if curiyr >= syr:
            j = int(ebptyp[b])
            nretir = _int(f32(f32(syr) + esbklf[j, n]))
            if j == EICAN:
                k = _int(f32(f32(f32(syr) + estxlf[j, n]) - one))
                if curiyr <= k:
                    temp1 = f32(estxlf[j, n] - f32(curiyr - syr))
                    temp2 = f32(f32(estxlf[j, n] * f32(estxlf[j, n] + one)) * half)
                    ertde2[n] = f32(f32(f32(temp1 / temp2) * ebasvl[b, n]) + ertde2[n])
            elif (syr >= irsyp and j <= EIPROD) or (syr >= irsytd and j > EIPROD):
                icuryr = curiyr - syr + 1
                if syr >= irsyt2 and j == EITRAN:
                    ertde2[n] = f32(ertde2[n] + f32(condrn[icuryr, 2, syr] * ebasvl[b, n]))
                else:
                    ertde2[n] = f32(ertde2[n] + f32(condrn[icuryr, int(icontp[j]), syr] * ebasvl[b, n]))
            else:
                l = _int(estxrc[j, n])
                k = curiyr - syr + 1
                if k <= estxrp[l]:
                    ertde2[n] = f32(ertde2[n] + f32(estxrs[l, k] * ebasvl[b, n]))
            # straight line tax depreciation
            if nretir >= curiyr:
                base = f32(ebasvl[b, n] * esdepr[j, n])
                ertdw2[n] = f32(ertdw2[n] + base)
                if syr == curiyr:
                    ertdw2[n] = f32(ertdw2[n] - f32(base * f32(one - ebserp[b])))
                if nretir == curiyr:
                    ertdw2[n] = f32(ertdw2[n] - f32(base * ebserp[b]))

    ertdwo[n] = f32(ertdwo[n] + ertdw2[n])
    ertde[n] = f32(ertde1[n] + ertde2[n])
    diff = f32(esftxr[n] * f32(ertde2[n] - ertdw2[n]))
    eratsf[n] = f32(eratsf[n] + f32(diff * esflpr[n]))
    eratsd[n] = f32(eratsd[n] + f32(diff * f32(one - esflpr[n])))
    erprdf[n] = f32(erpdfl[n] + eratsd[n])
    ertdrg[n] = f32(f32(ertdwo[n] * f32(one - esflpr[n])) + f32(ertde[n] * esflpr[n]))


def eltsaf(s):
    """Tax savings from the debt portion of AFUDC (ELTSAF)."""
    curiyr = i(s, "curiyr")
    efpsyr, uhbsyr = i(s, "efpsyr"), i(s, "uhbsyr")
    eovyrs = i(s, "eovyrs")
    estshr, esftxr = s["estshr"], s["esftxr"]
    eobklf, esbklf, eoafdc, ebafdc = s["eobklf"], s["esbklf"], s["eoafdc"], s["ebafdc"]
    erxfdc, erafdc, erprdf = s["erxfdc"], s["erafdc"], s["erprdf"]
    ebptyp, ebsyr = s["ebptyp"], s["ebsyr"]

    jy = max(efpsyr - uhbsyr + 1 - curiyr + 1, 1)
    for n in (1, 2):
        if estshr[n] == 0.0 or esftxr[n] == 0.0:
            continue
        eolafc = f32(0.0)
        enuafc = f32(0.0)
        for j in range(1, NPTYP + 1):
            for iyr in range(jy, eovyrs + 1):
                if curiyr < _old_retire(eobklf, j, n, iyr, efpsyr, uhbsyr):
                    eolafc = f32(eoafdc[iyr, j, n] + eolafc)
        for b in range(1, i(s, "ebnum") + 1):
            j = int(ebptyp[b])
            syr = int(ebsyr[b])
            nretir = _int(f32(f32(syr) + esbklf[j, n]))
            if curiyr >= syr and curiyr < nretir:
                enuafc = f32(ebafdc[b, n] + enuafc)
        erafdc[n] = f32(eolafc + enuafc)
        erprdf[n] = f32(f32(erprdf[n] + erxfdc[n]) - erafdc[n])
